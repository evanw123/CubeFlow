def _rotate_algorithms_to_slot(group: str, slot: str) -> list[F2LAlgorithm]:
    rotated: list[F2LAlgorithm] = []
    for algorithm in _FR_ALGORITHMS[group]:
        rotated.append(
            F2LAlgorithm(
                case_id=f"{algorithm.case_id}_{slot}",
                slot=slot,
                description=algorithm.description.replace("FR", slot),
                moves=map_slot_algorithm_from_fr(slot, algorithm.moves),
                display_moves=algorithm.display_moves[:],
                phase=algorithm.phase,
                source=algorithm.source,
            )
        )
    return rotated


def get_f2l_algorithms() -> list[F2LAlgorithm]:
    algorithms: list[F2LAlgorithm] = []
    for slot in ["FR", "FL", "BL", "BR"]:
        for group in _FR_ALGORITHMS:
            algorithms.extend(_rotate_algorithms_to_slot(group, slot))
    return algorithms


def get_basic_f2l_algorithms() -> list[F2LAlgorithm]:
    return get_f2l_algorithms()


def get_f2l_algorithms_for_case(case_code: str, slot: str) -> list[F2LAlgorithm]:
    case_to_group = {
        "PAIRED_TOP_READY": "INSERT_PAIRED_BACK",
        "PAIRED_ABOVE_WRONG_SLOT": "INSERT_PAIRED_BACK",
        "PAIRED_TOP_MISORIENTED": "INSERT_PAIRED_BACK",
        "PAIRED_INSERTABLE_FRONT": "INSERT_PAIRED_FRONT",
        "PAIRED_INSERTABLE_BACK": "INSERT_PAIRED_BACK",
        "PAIRED_TOP": "INSERT_PAIRED_BACK",
        "SEPARATE_TOP": "PAIR_SEPARATE_TOP",
        "CORNER_TOP_EDGE_MIDDLE": "EXTRACT",
        "EDGE_TOP_CORNER_SLOT": "EXTRACT",
        "INSERTED_BUT_TWISTED": "EXTRACT",
        "BOTH_INSERTED_WRONG": "EXTRACT",
        "BURIED_COMPLEX": "EXTRACT",
        "BURIED_OR_COMPLEX": "EXTRACT",
        "SOLVED": "INSERT_PAIRED_BACK",
    }

    group = case_to_group.get(case_code)
    if group is None:
        return []
    return _rotate_algorithms_to_slot(group, slot)


def get_algorithms_for_case(case_code: str, slot: str) -> list[F2LAlgorithm]:
    return get_f2l_algorithms_for_case(case_code, slot)
