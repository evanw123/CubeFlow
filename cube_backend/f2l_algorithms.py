from __future__ import annotations

from dataclasses import dataclass

from .move_utils import normalize_move_token, parse_alg


@dataclass
class F2LAlgorithm:
    case_id: str
    slot: str | None
    description: str
    moves: list[str]
    display_moves: list[str]
    phase: str
    source: str = "library"


# ---------------------------------------------------------------------------
# Slot normalization
# ---------------------------------------------------------------------------
#
# The canonical slot for the algorithm library is FR in the CFOP working view
# (white on D, yellow on U). Other slots are generated by rotating the
# canonical FR algorithms around the vertical axis.
#
# y turns are counted clockwise when looking down from U:
# - 0 turns: FR
# - 1 turn : BR
# - 2 turns: BL
# - 3 turns: FL

Y_ROTATION_FACE_MAP = {
    0: {"U": "U", "D": "D", "F": "F", "R": "R", "B": "B", "L": "L"},
    1: {"U": "U", "D": "D", "F": "R", "R": "B", "B": "L", "L": "F"},
    2: {"U": "U", "D": "D", "F": "B", "R": "L", "B": "F", "L": "R"},
    3: {"U": "U", "D": "D", "F": "L", "R": "F", "B": "R", "L": "B"},
}

SLOT_TO_Y_ROTATION = {
    "FR": 0,
    "BR": 1,
    "BL": 2,
    "FL": 3,
}


def slot_to_y_rotation(slot: str) -> int:
    return SLOT_TO_Y_ROTATION[slot]


def slot_to_y_rotation_prompt(slot: str) -> list[str]:
    prompts = {
        "FR": [],
        "FL": ["y"],
        "BL": ["y2"],
        "BR": ["y'"],
    }
    return prompts[slot][:]


def rotate_working_move_around_y(move: str, turns: int) -> str:
    normalized = normalize_move_token(move)
    face = normalized[0]
    suffix = normalized[1:]
    return Y_ROTATION_FACE_MAP[turns % 4][face] + suffix


def map_slot_algorithm_from_fr(slot: str, moves: list[str]) -> list[str]:
    turns = slot_to_y_rotation(slot)
    return [rotate_working_move_around_y(move, turns) for move in moves]


def rotate_algorithm_for_slot(base_slot: str, target_slot: str, moves: list[str]) -> list[str]:
    base_turns = slot_to_y_rotation(base_slot)
    target_turns = slot_to_y_rotation(target_slot)
    relative_turns = (target_turns - base_turns) % 4
    return [rotate_working_move_around_y(move, relative_turns) for move in moves]


